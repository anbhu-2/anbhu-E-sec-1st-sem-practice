#include<stdio.h>
int main()
{
int a,b;//5,6
scanf("%d%d",&a,&b);
printf("greater than=%d",a<b);//1
printf("less than=%d",a>b);//0
printf("equal to=%d",a==b);//0
printf("not equal to=%d",a!=b);//1
printf("greater than or equalto=%d",a<=b);//0
printf("less than or equalto=%d",a>=b);//0
printf("these are the relational operators thankyou");
return 0;
}
